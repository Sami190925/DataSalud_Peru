    Descripcion NVARCHAR(200) NOT NULL,
    Fuente VARCHAR(20) NOT NULL,
    Cantidad INT NOT NULL,
    Fecha DATETIME2(0) NOT NULL
        CONSTRAINT DF_log_Calidad_Fec DEFAULT SYSDATETIME()
);
GO

